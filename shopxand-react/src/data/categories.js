const LANG_INDEX = { ru: 0, tg: 1, en: 2 };

// Перевод пары [ru, tg, en] на текущий язык
export const pick = (triple, lang) => triple[LANG_INDEX[lang] ?? 0];

// Название категории товара (из базы) на текущем языке, если это категория из блоков
export const categoryLabel = (cat, lang) => {
  if (!cat) return cat;
  const block = BLOCKS.find(b => b.title[0] === cat);
  return block ? pick(block.title, lang) : cat;
};

const GENDER_WORDS = ['женск', 'мужск', 'детск'];

// Подходит ли товар под позицию списка (например, «Женские кроссовки»)
export const matchesItem = (product, ruText) => {
  const hay = ((product.name || '') + ' ' + (product.cat || '') + ' ' + (product.desc || '')).toLowerCase();
  const words = ruText.toLowerCase().replace(/[^a-zа-яё0-9\s-]/gi, ' ').split(/\s+/).filter(w => w.length >= 4);
  const stems = words
    .map(w => w.slice(0, Math.max(4, w.length - 2)))
    .filter(s => !GENDER_WORDS.some(g => s.startsWith(g)));
  const need = stems.length > 0 ? stems : words.map(w => w.slice(0, Math.max(4, w.length - 2)));
  if (need.length === 0) return false;
  return need.every(s => hay.includes(s));
};
